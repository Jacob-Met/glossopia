import assert from 'node:assert/strict';
import {pathToFileURL,fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const load=p=>import(pathToFileURL(root+'/src/'+p));
const {starterLanguage}=await load('starter-language.mjs');
const {validateVersion,proposeRevision,acceptRevision}=await load('language-core.mjs');
const patch=(id,order='SVO')=>({id,author:'reviewer',rationale:'Check identifier boundaries',order});
const languageId=('A9._-'.repeat(13)).slice(0,64);
assert.equal(languageId.length,64);
const nearLimit=validateVersion({...starterLanguage,languageId,versionId:'imported-v9999',number:9999,parentVersionId:'imported-v9998'});
const final=proposeRevision(nearLimit,patch('last-supported'));
assert.equal(final.candidate.number,10000);
assert.equal(final.candidate.versionId.length,64);
assert(final.candidate.versionId.endsWith('-v10000'));
assert.match(final.candidate.versionId,/^[A-Za-z][A-Za-z0-9._-]{0,63}$/);
assert.equal(final.candidate.languageId,languageId);
assert.equal(final.candidate.parentVersionId,'imported-v9999');
assert.throws(()=>proposeRevision(final.candidate,patch('past-limit','SOV')),e=>e.code==='VERSION_LIMIT');
console.log('PASS mixed allowed characters, 9999 to 10000 and terminal version bound');
const base=validateVersion({...starterLanguage,versionId:'luma-v2'});
const before=JSON.stringify(base),proposal=proposeRevision(base,patch('collision'));
assert.throws(()=>acceptRevision([base],proposal,{accept:true,author:'reviewer'}),e=>e.code==='DUPLICATE_VERSION');
assert.equal(JSON.stringify(base),before);
console.log('PASS arbitrary imported prior ID collision rejects without overwriting history');
