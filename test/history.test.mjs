import assert from 'node:assert/strict';
import {pathToFileURL,fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const load=p=>import(pathToFileURL(root+'/src/'+p));
const {starterLanguage}=await load('starter-language.mjs');
const {validateVersion,proposeRevision,acceptRevision}=await load('language-core.mjs');
const {createProject,serializeProject,parseProject}=await load('project.mjs');
const copy=v=>JSON.parse(JSON.stringify(v));
const base=copy(starterLanguage),before=JSON.stringify(base);
const proposal=proposeRevision(base,{id:'review-order',author:'reviewer',rationale:'Exercise order migration',order:'SVO'});
const history=acceptRevision([base],proposal,{accept:true,author:'reviewer'});
assert.equal(JSON.stringify(base),before);
assert.deepEqual(history[0],validateVersion(base));
assert(Object.isFrozen(history[0].examples[0].meaning));
assert.notEqual(history[1].examples[0].text,base.examples[0].text);
assert.throws(()=>acceptRevision(history,proposal,{accept:true,author:'reviewer'}),e=>e.code==='STALE_BASE');
const tamper=copy(proposal);tamper.candidate.lexicon[0].form='other';
assert.throws(()=>acceptRevision([base],tamper,{accept:true,author:'reviewer'}),e=>e.code==='PROPOSAL_MISMATCH');
const project=createProject(base);project.history=history;project.currentVersionId=history[1].versionId;
const roundtrip=parseProject(serializeProject(project));
assert.equal(roundtrip.sessions[0].versionId,base.versionId);
assert.deepEqual(roundtrip.history,history);
const broken=JSON.parse(serializeProject(project));broken.history[1].parentVersionId='missing';
assert.throws(()=>parseProject(JSON.stringify(broken)));
const falseMeaning=JSON.parse(serializeProject(project));falseMeaning.history[0].examples[0].meaning.quantity=99;
assert.throws(()=>parseProject(JSON.stringify(falseMeaning)));
console.log('PASS: historical immutability, migration, stale base, preview tampering, history/session roundtrip and malformed import');
